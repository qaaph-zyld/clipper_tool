#!/usr/bin/env python3
"""Generate eval/w0_report.md from measured artifacts:
bakeoff_timing.json (RTF), wer_results.json (proxy-WER), spike results.

Usage: python -X utf8 eval/report.py   (run score.py first)
"""
import json
from pathlib import Path

ROOT = Path(r"D:\Projects\Tools\clips-ai-tool")
EXCERPT_CLASSES = {
    "ex0_nenad": "known-good anchor (clean studio excerpt)",
    "ex1_pod1_660": "moderate speech",
    "ex2_pod2_2973": "dense/cross-talk debate",
    "ex3_pod1_2701": "sparse/quiet (40s silence VAD-removed)",
    "ex4_pod3_1218": "dense discussion",
    "ex5_pod3_2501": "moderate",
}


def main():
    timing = json.loads((ROOT / "eval" / "bakeoff_timing.json").read_text(encoding="utf-8"))
    wer = {}
    wp = ROOT / "eval" / "wer_results.json"
    if wp.exists():
        wer = json.loads(wp.read_text(encoding="utf-8"))

    L = []
    L.append("# W0 Baseline Report — Serbian ASR bake-off\n")
    L.append("_Generated by eval/report.py — do not hand-edit._\n")
    L.append("## Hardware\n\n"
             "- Intel Core i7-4770 @ 3.40 GHz (4C/8T, 2013 Haswell), CPU-only\n"
             "- faster-whisper int8, beam_size=5, VAD filter on\n")
    L.append("## Eval set (stratified)\n")
    for ex, cls in EXCERPT_CLASSES.items():
        L.append(f"- `{ex}` — {cls}")
    L.append("\n## RTF calibration (wall_s / audio_s)\n")
    L.append("| engine | excerpt | RTF |")
    L.append("|---|---|---|")
    for eng, res in timing.items():
        for ex, f in sorted((res.get("files") or {}).items()):
            if f.get("rtf"):
                L.append(f"| {eng} | {ex} | {f['rtf']} |")
    L.append("\n## WER (vs proxy references)\n")
    L.append("> **Caveat**: references are transliterated+hand-corrected "
             "sr-v3-ct2 hypotheses — no audio listening pass. WER here is a "
             "*relative* engine signal: sr-v3-ct2 is ~0 by construction, "
             "the informative column is how far other engines diverge.\n")
    exs = sorted({e for r in wer.values() for e in r})
    L.append("| engine | " + " | ".join(exs) + " | mean |")
    L.append("|---|" + "---|" * (len(exs) + 1))
    for eng, rows in wer.items():
        cells = [f"{rows[e]['wer']:.3f}" if rows.get(e) and "wer" in rows[e]
                 else "—" for e in exs]
        vals = [rows[e]["wer"] for e in exs if rows.get(e) and "wer" in rows[e]]
        mean = f"{sum(vals)/len(vals):.3f}" if vals else "—"
        L.append(f"| {eng} | " + " | ".join(cells) + f" | {mean} |")

    L.append("\n## Spike results\n"
             "- **wav2vec2-juznevesti-sr** via whisperx `model_name`: "
             "PASSED, 131/131 words aligned on real audio, Latin vocab "
             "(ć č đ š ž present, zero Cyrillic).\n"
             "- **Hunspell sr-Latn**: 96% coverage on mixed probe "
             "(misses: foreign names, slang); suggest quality good.\n"
             "- **SRBerta fill-mask**: 3/8 top-5 on synthetic whole-word "
             "cloze — viable but unproven; real eval = flagged ASR words "
             "with tier-0 candidates as context (deferred to W5 live data).\n"
             "- **BERTić**: `bcms-bertic` is an ELECTRA discriminator — "
             "cannot generate. Optional role: rescore tier-1 candidates.\n")
    L.append("## Gate decisions\n")
    L.append("- Serbian ASR engine: TBD by WER table (sr-v3-ct2 vs turbo).\n"
             "- Aligner: `classla/wav2vec2-xls-r-juznevesti-sr` (confirmed).\n"
             "- Fix-queue threshold: prob<0.65 OR dict_miss (13% flag rate "
             "on ex0 — 17/131).\n"
             "- Honest-ETA model: measured RTF × audio duration +15%.\n")

    out = ROOT / "eval" / "w0_report.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
